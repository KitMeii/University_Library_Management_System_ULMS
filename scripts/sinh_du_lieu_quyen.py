def doc_bang(tieu_de: str):
    text = SPEC.read_text(encoding="utf-8")
    i = text.index(tieu_de)
    dong = []
    for line in text[i:].splitlines()[1:]:
        if line.startswith("### ") or line.startswith("## "):
            break
        if line.startswith("|") and not line.startswith("|---"):
            dong.append([c.strip() for c in line.strip().strip("|").split("|")])
    return dong[1:]  # bỏ dòng tiêu đề


def cs(s: str) -> str:
    return '"' + s.replace("\\", "\\\\").replace('"', '\\"') + '"'


def ten_ngan(ten: str) -> str:
    if len(ten) <= 100:
        return ten
    # Cắt danh sách trường ở dấu phẩy gần nhất để tên vẫn phân biệt được (mô tả giữ đủ câu gốc).
    cat = ten[:97].rsplit(",", 1)[0]
    return cat + ", …)"


